# Temperature Parameter Explanation in Language Models:
# Temperature controls the randomness/creativity of model outputs (range: 0.0 to 1.0+):
# - Temperature = 0.0: Deterministic and factual (best for math, coding, precise answers)
# - Temperature = 0.7: Balanced creativity and coherence
# - Temperature = 1.0+: Highly creative, diverse, but potentially random responses